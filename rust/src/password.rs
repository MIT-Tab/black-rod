use std::num::NonZeroU32;

use argon2::{Argon2, PasswordHash, PasswordVerifier};
use base64::{Engine, engine::general_purpose::STANDARD};
use ring::{digest, pbkdf2};
use subtle::ConstantTimeEq;
use tokio::{sync::Semaphore, task::JoinError};

const ITERATIONS: NonZeroU32 = NonZeroU32::new(1_000_000).unwrap();
const SALT: &[u8] = b"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
static PASSWORD_WORKERS: Semaphore = Semaphore::const_new(4);

pub(crate) async fn run_blocking<T: Send + 'static>(
    operation: impl FnOnce() -> T + Send + 'static,
) -> Result<T, JoinError> {
    let permit = PASSWORD_WORKERS
        .acquire()
        .await
        .expect("password workers stay open");
    tokio::task::spawn_blocking(move || {
        let _permit = permit;
        operation()
    })
    .await
}

pub(crate) fn encode(password: &[u8]) -> Result<String, ring::error::Unspecified> {
    let salt = crate::session::random_token(SALT, 22)?;
    let mut output = [0; 32];
    pbkdf2::derive(
        pbkdf2::PBKDF2_HMAC_SHA256,
        ITERATIONS,
        salt.as_bytes(),
        password,
        &mut output,
    );
    Ok(format!(
        "pbkdf2_sha256${ITERATIONS}${salt}${}",
        STANDARD.encode(output)
    ))
}

fn pbkdf2_match(password: &[u8], encoded: &str, algorithm: pbkdf2::Algorithm) -> Option<bool> {
    let mut fields = encoded.split('$');
    let count = fields.next()?.parse::<NonZeroU32>().ok()?;
    let salt = fields.next()?;
    let expected = STANDARD.decode(fields.next()?).ok()?;
    let sha256 = algorithm == pbkdf2::PBKDF2_HMAC_SHA256;
    let length = if sha256 { 32 } else { 20 };
    if fields.next().is_some() || count.get() > 10_000_000 || expected.len() != length {
        return None;
    }
    let valid = pbkdf2::verify(algorithm, count, salt.as_bytes(), password, &expected).is_ok();
    if !valid
        && sha256
        && let Some(extra) = NonZeroU32::new(ITERATIONS.get().saturating_sub(count.get()))
    {
        // Match Django's harden_runtime for an outdated default hasher.
        pbkdf2::derive(algorithm, extra, salt.as_bytes(), password, &mut [0; 32]);
    }
    Some(valid)
}

fn scrypt_match(password: &[u8], encoded: &str) -> Option<bool> {
    let mut fields = encoded.split('$');
    let work = fields.next()?.parse::<u32>().ok()?;
    let salt = fields.next()?;
    let block = fields.next()?.parse().ok()?;
    let parallelism = fields.next()?.parse().ok()?;
    let expected = STANDARD.decode(fields.next()?).ok()?;
    if fields.next().is_some() || expected.len() != 64 || !work.is_power_of_two() {
        return None;
    }
    let params = scrypt::Params::new(
        work.ilog2().try_into().ok()?,
        block,
        parallelism,
        expected.len(),
    )
    .ok()?;
    let mut hash = [0; 64];
    scrypt::scrypt(password, salt.as_bytes(), &params, &mut hash).ok()?;
    Some(bool::from(hash.ct_eq(&expected)))
}

fn check(password: &[u8], encoded: &str) -> Option<bool> {
    let (algorithm, rest) = encoded.split_once('$')?;
    match algorithm {
        "pbkdf2_sha256" => pbkdf2_match(password, rest, pbkdf2::PBKDF2_HMAC_SHA256),
        "pbkdf2_sha1" => pbkdf2_match(password, rest, pbkdf2::PBKDF2_HMAC_SHA1),
        "argon2" => {
            let phc = format!("${rest}");
            let parsed = PasswordHash::new(&phc).ok()?;
            Some(Argon2::default().verify_password(password, &parsed).is_ok())
        }
        "bcrypt_sha256" => {
            let prehash = hex::encode(digest::digest(&digest::SHA256, password));
            bcrypt::verify(prehash.as_bytes(), rest).ok()
        }
        "scrypt" => scrypt_match(password, rest),
        _ => None,
    }
}

pub(crate) fn verify_and_upgrade(password: &[u8], stored: Option<&str>) -> Option<Option<String>> {
    // Django does a default-cost hash for nonexistent accounts and unusable hashes.
    let checked = stored.and_then(|hash| check(password, hash));
    let Some(valid) = checked else {
        let _ = encode(password);
        return None;
    };
    if !valid {
        return None;
    }
    let upgrade = stored.is_some_and(|hash| {
        let mut parts = hash.split('$');
        parts.next() != Some("pbkdf2_sha256")
            || parts
                .next()
                .and_then(|count| count.parse::<NonZeroU32>().ok())
                != Some(ITERATIONS)
            || parts.next().is_none_or(|salt| salt.len() < 22)
    });
    Some(if upgrade { encode(password).ok() } else { None })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn verifies_django_pbkdf2_sha1_and_scrypt_encodings() {
        // Generated by Django using disposable passwords and fixed test salts.
        for original in [
            "pbkdf2_sha1$6500$F1xfA8YK4HXaDw$5En+rCZ95DFckH9BeVa/2xMQF6w=",
            "scrypt$16$RustDjango$8$1$+eEbTlHF6GfryFBk27riCHrFaPQbewuiufaGXCZCECVCyvAOL+8HM80ENvRG30r+s8IRoGgjXgDmWE3REEAmaw==",
        ] {
            assert_eq!(check(b"disposable", original), Some(true), "{original}");
            assert_eq!(check(b"incorrect", original), Some(false), "{original}");
        }
    }
    #[test]
    fn rejects_truncated_pbkdf2_hashes() {
        let mut expected = [0; 32];
        let count = NonZeroU32::new(1).unwrap();
        pbkdf2::derive(
            pbkdf2::PBKDF2_HMAC_SHA256,
            count,
            b"fixture",
            b"password",
            &mut expected,
        );
        let full = format!("pbkdf2_sha256$1$fixture${}", STANDARD.encode(expected));
        let partial = format!(
            "pbkdf2_sha256$1$fixture${}",
            STANDARD.encode(&expected[..1])
        );
        assert_eq!(check(b"password", &full), Some(true));
        assert_eq!(check(b"password", &partial), None);
    }

    #[test]
    fn rejects_hashes_outside_djangos_configured_hashers() {
        assert_eq!(
            check(
                b"disposable",
                "md5$RustDjango$b839a3f4a1161cb7a2bd92ba4ac69d34"
            ),
            None
        );
        assert_eq!(check(b"disposable", "bcrypt$unused"), None);
    }
}
